# Docs: docs/03 - Features/Certificates.md
# Builds the DNS provider list from lego's provider files (Traefik uses lego for ACME).
# Usage: python3 -I tools/gen_dns_providers.py <lego checkout> <lego version>
"""Writes web/src/ui/dnsProviders.ts and the downloaded docs page. Rerun when the Traefik version changes."""
import glob, json, os, re, sys, tomllib

src, version = sys.argv[1], sys.argv[2]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENV = re.compile(r"^[A-Z][A-Z0-9_]*$")

# lego lists alternatives together (a token, or an email and a key). For these, the usual way to sign in is what opens first.
NEEDED = {
    "azuredns": ["AZURE_CLIENT_ID", "AZURE_CLIENT_SECRET", "AZURE_TENANT_ID"],
    "cloudflare": ["CF_DNS_API_TOKEN"],
    "gandiv5": ["GANDIV5_PERSONAL_ACCESS_TOKEN"],
    "gcloud": ["GCE_PROJECT", "GCE_SERVICE_ACCOUNT_FILE"],
    "ovh": ["OVH_ENDPOINT", "OVH_APPLICATION_KEY", "OVH_APPLICATION_SECRET", "OVH_CONSUMER_KEY"],
    "route53": ["AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_REGION"],
}
SKIP = {"manual"}  # asks a person to act on the command line: can't work inside a container

rows = []
for path in glob.glob(os.path.join(src, "**", "providers", "dns", "*", "*.toml"), recursive=True):
    d = tomllib.load(open(path, "rb"))
    if d["Code"] in SKIP:
        continue
    creds = [k for k in d.get("Configuration", {}).get("Credentials", {}) if ENV.match(k)]
    env = NEEDED.get(d["Code"], creds)
    assert all(k in creds for k in env), d["Code"]
    rows.append({"code": d["Code"], "name": d["Name"], "env": env, "all": creds, "url": d.get("URL", ""), "sure": d["Code"] in NEEDED})
rows.sort(key=lambda r: r["name"].lower())
assert len(rows) > 100

with open(os.path.join(root, "web/src/ui/dnsProviders.ts"), "w", encoding="utf-8") as f:
    f.write("// Docs: docs/03 - Features/Certificates.md\n")
    f.write(f"// Generated by tools/gen_dns_providers.py from lego {version}. Don't edit by hand.\n")
    f.write("export interface DNSProvider {\n  code: string;\n  name: string;\n  env: string[];\n  // sure: env is exactly what the usual sign-in needs. Otherwise lego may list alternatives.\n  sure?: boolean;\n}\n\n")
    f.write("export const DNS_PROVIDERS: DNSProvider[] = [\n")
    for r in rows:
        item = {"code": r["code"], "name": r["name"], "env": r["env"]}
        if r["sure"]:
            item["sure"] = True
        f.write("  " + json.dumps(item, ensure_ascii=False) + ",\n")
    f.write("];\n")

out = os.path.join(root, "docs/00 - Downloaded Docs/lego")
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "DNS providers.md"), "w", encoding="utf-8") as f:
    f.write(f"# DNS providers\n\nSource: `providers/dns/*/*.toml` of lego {version}. The code is what Traefik's `dnsChallenge.provider` takes.\n\n")
    f.write("| Provider | Code | Credentials |\n|---|---|---|\n")
    for r in rows:
        name = r["name"].replace("|", "\\|")
        f.write(f"| {name} | `{r['code']}` | {', '.join('`' + k + '`' for k in r['all'])} |\n")
print(len(rows), "providers")
